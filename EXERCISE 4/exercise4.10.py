# Menampilkan tiga elemen pertama, tiga elemen tengah, dan tiga elemen terakhir dari sebuah list menggunakan slice
mountains = ["Mount Everest", "Mount Fuji", "Mount Bromo","Mount Rinjani", "Mount Merapi", "Mount Semeru", "Mount Kilimanjaro"]

print("The first three items in the list are:")
print(mountains[:3])

print("\nThree items from the middle of the list are:")
print(mountains[2:5])

print("\nThe last three items in the list are:")
print(mountains[-3:])
# Menggunakan struktur if-else untuk menentukan poin berdasarkan warna alien
# Kondisi true = 5 poin
alien_color = "green"

if alien_color == "green":
    print("You received 5 points!")
else:
    print("You received 10 points!")
    
# Kondisi false = 10 poin
alien_color = "yellow"

if alien_color == "green":
    print("You received 5 points!")
else:
    print("You received 10 points!")
# Membuat serangkaian pengujian kondisi (conditional tests). Setiap pengujian harus menampilkan pernyataan dan prediksi hasilnya, kemudian menampilkan hasil sebenarnya (True atau False)
car = "Toyota"

print("Is car == 'Toyota'? I predict True.")
print(car == "Toyota")

print("\nIs car == 'Honda'? I predict False.")
print(car == "Honda")

food = "Pizza"

print("\nIs food == 'Pizza'? I predict True.")
print(food == "Pizza")

print("\nIs food == 'Burger'? I predict False.")
print(food == "Burger")

age = 20

print("\nIs age == 20? I predict True.")
print(age == 20)

print("\nIs age != 20? I predict False.")
print(age != 20)

color = "Blue"

print("\nIs color == 'Blue'? I predict True.")
print(color == "Blue")

print("\nIs color == 'Red'? I predict False.")
print(color == "Red")

number = 15

print("\nIs number > 10? I predict True.")
print(number > 10)

print("\nIs number < 10? I predict False.")
print(number < 10)
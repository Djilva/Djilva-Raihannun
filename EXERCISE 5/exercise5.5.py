# Mengubah program 5-4 menjadi struktur if-elif-else dengan tiga warna alien
# Alien berwarna hijau = 5 poin
alien_color = "green"

if alien_color == "green":
    print("You earned 5 points!")
elif alien_color == "yellow":
    print("You earned 10 points!")
else:
    print("You earned 15 points!")

